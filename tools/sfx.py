def fx_storm_off(rng):
    """A customer storms off: an annoyed grumble and the door slamming."""
    n = int(0.32 * RATE)
    freqs = [115.0 * (1.0 + 0.08 * math.sin(2 * math.pi * 9.0 * i / RATE)) for i in range(n)]
    grumble = lowpass(oscillate(freqs, saw), [900.0] * n)
    buf = [s * e * 0.6 for s, e in zip(grumble, envelope(n, 0.02, 0.1))]
    place(buf, thump(70.0, 0.2), 0.3, 1.0)
    return place(buf, noise(0.08, rng, [(0, 2200), (1, 500)]), 0.3, 0.5)


def fx_refuse(rng):
    """The player refuses a customer: a two-note "nuh-uh"."""
    a = lowpass(sweep(note_hz(E4), note_hz(E4), 0.12, square, 0.005, 0.04), [1200.0] * int(0.12 * RATE))
    b = lowpass(sweep(note_hz(C4), note_hz(C4) * 0.97, 0.18, square, 0.005, 0.1), [1200.0] * int(0.18 * RATE))
    return place(list(a), b, 0.13)


