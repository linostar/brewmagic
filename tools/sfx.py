def fx_wave(rng):
    """A Rush Hour wave starts: a short brassy fanfare over a drum hit."""
    buf = thump(100.0, 0.2)
    for at, semis, length in ((0.0, C5, 0.12), (0.12, E5, 0.12), (0.24, G5, 0.12), (0.36, C6, 0.5)):
        n = int(length * RATE)
        tone = lowpass(sweep(note_hz(semis), note_hz(semis), length, lambda p: 1.0 if p < 0.3 else -1.0, 0.006, 0.08),
                       [2400.0] * n)
        place(buf, tone, at, 0.5)
    return buf


def fx_rush_over(rng):
    """A Rush Hour run ends: a falling, sighing sting."""
    buf = []
    for i, semis in enumerate((G4, G4 - 1, G4 - 2)):
        place(buf, lowpass(sweep(note_hz(semis), note_hz(semis), 0.22, saw, 0.01, 0.06), [1500.0] * int(0.22 * RATE)), i * 0.24)
    n = int(0.6 * RATE)
    freqs = [note_hz(G4 - 3) * (1.0 + 0.025 * math.sin(2 * math.pi * 6.0 * i / RATE)) * (1.0 - 0.04 * i / n) for i in range(n)]
    last = lowpass(oscillate(freqs, saw), [1500.0] * n)
    return place(buf, [s * e for s, e in zip(last, envelope(n, 0.01, 0.3))], 0.72)


