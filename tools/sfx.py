#!/usr/bin/env python3
"""Synthesises BrewMagic's sound effects as 16-bit mono WAV.

Standard library only and fully deterministic (fixed seeds, no clock), so the committed
files can always be regenerated byte-for-byte. Synth core ported from Silly Kitty
(../jamference-20261002/tools/sfx.py): one-pole low-pass, linear envelopes, piecewise
curves, peak-normalised 16-bit writer.

Sounds so far (the full set comes with the audio pass, plan step 9):
    voice_<archetype>.wav   one short voice blip per archetype in brewmagic/data/archetypes.json,
                            its pitch and timbre from the archetype's "voice" (data/SCHEMA.md);
                            the speech bubble plays it every few typed characters.

Usage (from repo root):
    python3 tools/sfx.py           write every sound into brewmagic/audio/sfx/
    python3 tools/sfx.py --check   regenerate in memory and verify the committed files are
                                   byte-identical and none is stale; prints "sfx: OK"
"""
import io
import json
import math
import random
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "brewmagic" / "audio" / "sfx"
ARCHETYPES = ROOT / "brewmagic" / "data" / "archetypes.json"
RATE = 22050
PEAK = 0.9
# Voice blips sit under the other effects.
VOICE_PEAK = 0.55
# A pitch 1.0 voice's fundamental in Hz.
VOICE_BASE_HZ = 240.0
VOICE_SECONDS = 0.075
TIMBRES = ("reed", "bell", "growl", "chirp")


class SfxError(Exception):
    pass


def lowpass(samples, cutoffs):
    """One-pole low-pass filter with a per-sample cutoff in Hz."""
    out, y = [], 0.0
    for x, fc in zip(samples, cutoffs):
        y += (1.0 - math.exp(-2.0 * math.pi * fc / RATE)) * (x - y)
        out.append(y)
    return out


def envelope(n, attack, release):
    """Linear attack, then linear release over the last `release` seconds."""
    a, r = max(1, int(attack * RATE)), max(1, int(release * RATE))
    return [min(1.0, i / a, (n - i) / r) for i in range(n)]


def lerp_curve(points, n):
    """Piecewise-linear curve through (time_fraction, value) points."""
    out = []
    for i in range(n):
        t = i / max(1, n - 1)
        for (t0, v0), (t1, v1) in zip(points, points[1:]):
            if t0 <= t <= t1:
                out.append(v0 + (v1 - v0) * (t - t0) / max(1e-9, t1 - t0))
                break
    return out


def oscillate(freqs, shape):
    """A wave following the per-sample frequency curve `freqs`; shape(phase 0..1) -> -1..1."""
    phase, out = 0.0, []
    for f in freqs:
        phase = (phase + f / RATE) % 1.0
        out.append(shape(phase))
    return out


def voice(pitch, timbre, rng):
    """One "blah" syllable of a customer's voice: a short pitched blip whose timbre is
    reed (nasal pulse), bell (sine with an inharmonic partial), growl (buzzy, wobbling
    saw) or chirp (a quick upward sine sweep)."""
    n = int(VOICE_SECONDS * RATE)
    f0 = VOICE_BASE_HZ * pitch
    if timbre == "reed":
        freqs = lerp_curve([(0, f0 * 1.05), (1, f0 * 0.95)], n)
        raw = oscillate(freqs, lambda p: 1.0 if p < 0.3 else -0.45)
        raw = lowpass(raw, [2600.0] * n)
        env = envelope(n, 0.006, 0.03)
    elif timbre == "bell":
        raw = [math.sin(2 * math.pi * 2 * f0 * i / RATE) + 0.45 * math.sin(2 * math.pi * 5.4 * f0 * i / RATE)
               * math.exp(-40.0 * i / RATE) for i in range(n)]
        env = [min(1.0, i / 40) * math.exp(-22.0 * i / RATE) for i in range(n)]
    elif timbre == "growl":
        freqs = lerp_curve([(0, f0 * 0.9), (1, f0 * 0.8)], n)
        saw = oscillate(freqs, lambda p: 2.0 * p - 1.0)
        raw = [s * (0.7 + 0.3 * math.sin(2 * math.pi * 32.0 * i / RATE)) + rng.uniform(-0.25, 0.25)
               for i, s in enumerate(saw)]
        raw = lowpass(raw, [1300.0] * n)
        env = envelope(n, 0.008, 0.035)
    elif timbre == "chirp":
        freqs = lerp_curve([(0, f0 * 1.6), (1, f0 * 2.4)], n)
        raw = oscillate(freqs, lambda p: math.sin(2 * math.pi * p))
        env = envelope(n, 0.004, 0.03)
    else:
        raise SfxError(f"unknown timbre '{timbre}' (known: {', '.join(TIMBRES)})")
    return [s * e for s, e in zip(raw, env)]


def wav_bytes(samples, peak=PEAK):
    top = max(abs(s) for s in samples) or 1.0
    frames = b"".join(struct.pack("<h", int(s / top * peak * 32767)) for s in samples)
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(frames)
    return buffer.getvalue()


def sounds():
    """{file name: WAV bytes} for every sound, in a fixed order."""
    try:
        archetypes = json.loads(ARCHETYPES.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise SfxError(f"cannot read {ARCHETYPES.relative_to(ROOT)}: {e}")
    files = {}
    for entry in archetypes:
        try:
            who, pitch, timbre = entry["id"], float(entry["voice"]["pitch"]), entry["voice"]["timbre"]
        except (KeyError, TypeError, ValueError) as e:
            raise SfxError(f"archetype {entry.get('id', '?') if isinstance(entry, dict) else entry!r}: bad voice ({e})")
        # Each voice has its own noise seed, so adding an archetype never changes the others.
        rng = random.Random(f"voice/{who}")
        files[f"voice_{who}.wav"] = wav_bytes(voice(pitch, timbre, rng), VOICE_PEAK)
    return files


def check():
    files = sounds()
    problems = []
    for name, data in files.items():
        committed = OUT_DIR / name
        if not committed.exists():
            problems.append(f"{committed.relative_to(ROOT)} missing, run python3 tools/sfx.py")
        elif committed.read_bytes() != data:
            problems.append(f"{committed.relative_to(ROOT)} differs from its synth, run python3 tools/sfx.py")
    for path in sorted(OUT_DIR.glob("*.wav")):
        if path.name not in files:
            problems.append(f"{path.relative_to(ROOT)} is stale: no sound makes it any more")
    if problems:
        raise SfxError("\n".join(problems))
    print(f"sfx: OK ({len(files)} sounds)")


def main():
    try:
        if sys.argv[1:] == ["--check"]:
            check()
        elif not sys.argv[1:]:
            OUT_DIR.mkdir(parents=True, exist_ok=True)
            files = sounds()
            for name, data in files.items():
                (OUT_DIR / name).write_bytes(data)
            print(f"sfx: wrote {len(files)} sounds to {OUT_DIR.relative_to(ROOT)}")
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except SfxError as e:
        print(f"sfx: error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
