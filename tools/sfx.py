#!/usr/bin/env python3
"""Synthesises BrewMagic's sound effects as 16-bit mono WAV.

Standard library only and fully deterministic (fixed seeds, no clock), so the committed
files can always be regenerated byte-for-byte. Synth core ported from Silly Kitty
(../jamference-20261002/tools/sfx.py): one-pole low-pass, linear envelopes, piecewise
curves, peak-normalised 16-bit writer.

Sounds:
    voice_<archetype>.wav   one short voice blip per archetype in brewmagic/data/archetypes.json,
                            its pitch and timbre from the archetype's "voice" (data/SCHEMA.md);
                            the speech bubble plays it every few typed characters.
    <name>.wav              every game sound effect of EFFECTS (one generator each, its own
                            noise seed and peak level), played through Game.sfx(name); the
                            list is GameState.SFX_IDS (a test checks both agree).

Every file is peak-normalised to its own level, never above PEAK, so nothing clips;
the levels set the mix (voices and taps quiet, stamps and stingers loudest).

Usage (from repo root):
    python3 tools/sfx.py           write every sound into brewmagic/audio/sfx/
    python3 tools/sfx.py --check   regenerate in memory and verify the committed files are
                                   byte-identical and none is stale; prints "sfx: OK"
"""
import io
import json
import math
import random
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "brewmagic" / "audio" / "sfx"
ARCHETYPES = ROOT / "brewmagic" / "data" / "archetypes.json"
RATE = 22050
PEAK = 0.9
# Voice blips sit under the other effects.
VOICE_PEAK = 0.55
# A pitch 1.0 voice's fundamental in Hz.
VOICE_BASE_HZ = 240.0
VOICE_SECONDS = 0.075
TIMBRES = ("reed", "bell", "growl", "chirp")


class SfxError(Exception):
    pass


def lowpass(samples, cutoffs):
    """One-pole low-pass filter with a per-sample cutoff in Hz."""
    out, y = [], 0.0
    for x, fc in zip(samples, cutoffs):
        y += (1.0 - math.exp(-2.0 * math.pi * fc / RATE)) * (x - y)
        out.append(y)
    return out


def envelope(n, attack, release):
    """Linear attack, then linear release over the last `release` seconds."""
    a, r = max(1, int(attack * RATE)), max(1, int(release * RATE))
    return [min(1.0, i / a, (n - i) / r) for i in range(n)]


def lerp_curve(points, n):
    """Piecewise-linear curve through (time_fraction, value) points."""
    out = []
    for i in range(n):
        t = i / max(1, n - 1)
        for (t0, v0), (t1, v1) in zip(points, points[1:]):
            if t0 <= t <= t1:
                out.append(v0 + (v1 - v0) * (t - t0) / max(1e-9, t1 - t0))
                break
    return out


def oscillate(freqs, shape):
    """A wave following the per-sample frequency curve `freqs`; shape(phase 0..1) -> -1..1."""
    phase, out = 0.0, []
    for f in freqs:
        phase = (phase + f / RATE) % 1.0
        out.append(shape(phase))
    return out


def voice(pitch, timbre, rng):
    """One "blah" syllable of a customer's voice: a short pitched blip whose timbre is
    reed (nasal pulse), bell (sine with an inharmonic partial), growl (buzzy, wobbling
    saw) or chirp (a quick upward sine sweep)."""
    n = int(VOICE_SECONDS * RATE)
    f0 = VOICE_BASE_HZ * pitch
    if timbre == "reed":
        freqs = lerp_curve([(0, f0 * 1.05), (1, f0 * 0.95)], n)
        raw = oscillate(freqs, lambda p: 1.0 if p < 0.3 else -0.45)
        raw = lowpass(raw, [2600.0] * n)
        env = envelope(n, 0.006, 0.03)
    elif timbre == "bell":
        raw = [math.sin(2 * math.pi * 2 * f0 * i / RATE) + 0.45 * math.sin(2 * math.pi * 5.4 * f0 * i / RATE)
               * math.exp(-40.0 * i / RATE) for i in range(n)]
        env = [min(1.0, i / 40) * math.exp(-22.0 * i / RATE) for i in range(n)]
    elif timbre == "growl":
        freqs = lerp_curve([(0, f0 * 0.9), (1, f0 * 0.8)], n)
        saw = oscillate(freqs, lambda p: 2.0 * p - 1.0)
        raw = [s * (0.7 + 0.3 * math.sin(2 * math.pi * 32.0 * i / RATE)) + rng.uniform(-0.25, 0.25)
               for i, s in enumerate(saw)]
        raw = lowpass(raw, [1300.0] * n)
        env = envelope(n, 0.008, 0.035)
    elif timbre == "chirp":
        freqs = lerp_curve([(0, f0 * 1.6), (1, f0 * 2.4)], n)
        raw = oscillate(freqs, lambda p: math.sin(2 * math.pi * p))
        env = envelope(n, 0.004, 0.03)
    else:
        raise SfxError(f"unknown timbre '{timbre}' (known: {', '.join(TIMBRES)})")
    return [s * e for s, e in zip(raw, env)]


def silence(seconds):
    return [0.0] * int(seconds * RATE)


def place(buf, samples, at, gain=1.0):
    """Adds `samples` into `buf` from `at` seconds on, growing `buf` as needed."""
    start = int(at * RATE)
    if len(buf) < start + len(samples):
        buf.extend([0.0] * (start + len(samples) - len(buf)))
    for i, s in enumerate(samples):
        buf[start + i] += s * gain
    return buf


def ping(freq, seconds, decay, partials=((1.0, 1.0),), attack=0.002):
    """A struck tone: sine partials (frequency multiple, amplitude) under an exponential decay."""
    n, a = int(seconds * RATE), max(1, int(attack * RATE))
    return [min(1.0, i / a) * math.exp(-decay * i / RATE)
            * sum(amp * math.sin(2 * math.pi * freq * mult * i / RATE) for mult, amp in partials)
            for i in range(n)]


def sweep(start_hz, end_hz, seconds, shape, attack, release):
    """A tone gliding from start_hz to end_hz with a linear envelope."""
    n = int(seconds * RATE)
    raw = oscillate(lerp_curve([(0, start_hz), (1, end_hz)], n), shape)
    return [s * e for s, e in zip(raw, envelope(n, attack, release))]


def noise(seconds, rng, cutoffs, decay=0.0, attack=0.002, release=0.02):
    """Low-passed white noise; `cutoffs` is a lerp_curve point list for the cutoff in Hz."""
    n = int(seconds * RATE)
    raw = lowpass([rng.uniform(-1.0, 1.0) for _ in range(n)], lerp_curve(cutoffs, n))
    env = envelope(n, attack, release)
    return [s * e * math.exp(-decay * i / RATE) for i, (s, e) in enumerate(zip(raw, env))]


def thump(freq=110.0, seconds=0.16):
    """A soft low drum hit: a sine falling an octave, decaying fast."""
    n, phase, out = int(seconds * RATE), 0.0, []
    for i in range(n):
        phase += freq * (1.0 + math.exp(-30.0 * i / RATE)) / RATE
        out.append(math.sin(2 * math.pi * phase) * math.exp(-18.0 * i / RATE))
    return out


def sine(p):
    return math.sin(2 * math.pi * p)


def square(p):
    return 1.0 if p < 0.5 else -1.0


def triangle(p):
    return 4.0 * abs(p - 0.5) - 1.0


def saw(p):
    return 2.0 * p - 1.0


BELL = ((1.0, 1.0), (2.76, 0.35), (5.4, 0.15))
GLASS = ((1.0, 1.0), (2.4, 0.4))
COIN = ((1.0, 1.0), (1.48, 0.6), (2.9, 0.25))


def note_hz(semitones_from_a4):
    return 440.0 * 2 ** (semitones_from_a4 / 12)


# Notes used below, as semitones from A4.
C4, E4, G4, C5, E5, G5, B5, C6, D6, E6, G6 = -9, -5, -2, 3, 7, 10, 14, 15, 17, 19, 22


def arpeggio(notes, gap, seconds, decay, partials):
    buf = []
    for i, semis in enumerate(notes):
        place(buf, ping(note_hz(semis), seconds, decay, partials), i * gap)
    return buf


def fx_tap(rng):
    """A button press: a short woody click."""
    buf = [s * 0.8 for s in sweep(1300.0, 700.0, 0.035, triangle, 0.001, 0.025)]
    return place(buf, noise(0.012, rng, [(0, 4000), (1, 1500)]), 0.0, 0.4)


def fx_drop(rng):
    """An ingredient leaving the shelf for the pot: a rising bloop."""
    return sweep(320.0, 760.0, 0.11, sine, 0.004, 0.06)


def fx_splash(rng):
    """The ingredient landing in the cauldron: a splash and a bubble."""
    buf = noise(0.26, rng, [(0, 3200), (0.4, 1400), (1, 500)], decay=9.0)
    return place(buf, sweep(480.0, 900.0, 0.08, sine, 0.004, 0.05), 0.05, 0.6)


def fx_slot_remove(rng):
    """An ingredient taken back out of the pot: a falling plip."""
    return sweep(820.0, 360.0, 0.1, sine, 0.003, 0.05)


def fx_stir(rng):
    """One stir rotation: a liquid swish with a slosh under it."""
    buf = noise(0.24, rng, [(0, 400), (0.5, 1700), (1, 400)], attack=0.08, release=0.12)
    slosh = [math.sin(2 * math.pi * (170.0 + 30.0 * math.sin(2 * math.pi * 6.0 * i / RATE)) * i / RATE)
             * math.sin(math.pi * i / (0.24 * RATE)) for i in range(int(0.24 * RATE))]
    return place(buf, slosh, 0.0, 0.35)


def fx_pour_fill(rng):
    """A bottle filling (plays from pour_start until the pour stops): glugs rising in pitch
    as the bottle fills, over a rising trickle; it lasts past the 1.875 s spill point."""
    seconds = 1.95
    buf = noise(seconds, rng, [(0, 500), (1, 2400)], attack=0.05, release=0.08)
    buf = [s * 0.35 for s in buf]
    at, k = 0.02, 0
    while at < seconds - 0.1:
        f = 260.0 + 620.0 * at / seconds
        place(buf, sweep(f, f * 1.5, 0.06, sine, 0.003, 0.04), at, 0.8)
        at += 0.085 + 0.02 * ((k * 7) % 3)
        k += 1
    return buf


def fx_pour_stop(rng):
    """The pour released: a glass tink."""
    return ping(1760.0, 0.16, 26.0, GLASS)


def fx_pour_spill(rng):
    """Past the brim: a splatter of drips."""
    buf = noise(0.42, rng, [(0, 2400), (1, 700)], decay=4.0)
    for at in (0.0, 0.07, 0.15, 0.24):
        place(buf, sweep(700.0, 300.0, 0.05, sine, 0.002, 0.03), at, 0.5)
    return buf


def fx_mortar(rng):
    """A pestle stroke: gritty grinding over a low knock."""
    n = int(0.17 * RATE)
    grit = noise(0.17, rng, [(0, 1900), (1, 1200)], attack=0.01, release=0.06)
    grit = [s * (0.55 + 0.45 * math.sin(2 * math.pi * 55.0 * i / RATE)) for i, s in enumerate(grit[:n])]
    return place(grit, thump(130.0, 0.1), 0.0, 0.5)


def fx_bellows_pump(rng):
    """A bellows squeeze: a breathy whoosh."""
    return noise(0.18, rng, [(0, 400), (0.45, 2600), (1, 700)], attack=0.03, release=0.09)


def fx_bellows_out(rng):
    """The needle left the band: a low two-step warning buzz."""
    buf = [s * 0.7 for s in lowpass(sweep(220.0, 210.0, 0.12, square, 0.004, 0.03), [900.0] * int(0.12 * RATE))]
    return place(buf, lowpass(sweep(165.0, 150.0, 0.16, square, 0.004, 0.06), [900.0] * int(0.16 * RATE)), 0.13, 0.7)


def fx_success(rng):
    """A station done well: a bright rising chime."""
    return arpeggio([C6, E6, G6], 0.06, 0.25, 14.0, BELL)


def fx_sloppy(rng):
    """A station done sloppily: a wobbly falling wah."""
    n = int(0.4 * RATE)
    freqs = [(420.0 - 170.0 * i / n) * (1.0 + 0.04 * math.sin(2 * math.pi * 7.0 * i / RATE)) for i in range(n)]
    raw = lowpass(oscillate(freqs, triangle), [1600.0] * n)
    return [s * e for s, e in zip(raw, envelope(n, 0.01, 0.18))]


def stamp(rng, tune):
    """A grade stamp: an inky thump, then the grade's own little tune."""
    buf = thump(95.0, 0.18)
    buf = place(buf, noise(0.05, rng, [(0, 1800), (1, 600)]), 0.0, 0.4)
    return place(buf, tune, 0.05, 0.8)


def fx_stamp_perfect(rng):
    return stamp(rng, arpeggio([C5, E5, G5, C6], 0.06, 0.35, 9.0, BELL))


def fx_stamp_good(rng):
    return stamp(rng, arpeggio([G5, C6], 0.08, 0.3, 11.0, BELL))


def fx_stamp_meh(rng):
    n = int(0.3 * RATE)
    raw = oscillate([note_hz(E5) * (1.0 - 0.05 * i / n) for i in range(n)], triangle)
    return stamp(rng, [s * e for s, e in zip(raw, envelope(n, 0.005, 0.2))])


def fx_stamp_misbrew(rng):
    n = int(0.36 * RATE)
    return stamp(rng, [s * 0.8 for s in lowpass(sweep(300.0, 140.0, 0.36, square, 0.004, 0.12), [1400.0] * n)])


def fx_coins(rng):
    """Pay received: a jingle of coins."""
    buf = []
    for at, f in ((0.0, 2600.0), (0.05, 3150.0), (0.11, 2800.0), (0.17, 3400.0)):
        place(buf, ping(f, 0.2, 22.0, COIN), at, 0.7)
    return buf


