    """A tip on top: a quick sparkle going up."""
    buf = []
    for i, f in enumerate((2000.0, 2500.0, 3000.0, 3800.0)):
        place(buf, ping(f, 0.14, 26.0, GLASS), i * 0.045, 0.6)
    return buf


