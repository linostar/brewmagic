#!/usr/bin/env python3
"""Compiles the palette-indexed sprite sources in art_src/*.px into PNG atlases.

Standard library only and fully deterministic, so the committed atlases can always be
regenerated byte-for-byte.

Palette: art_src/palette.hex, exactly 32 unique '#rrggbb' lines in index order.
';' starts a comment (whole line or after the colour).

Sprite source (.px), one file = one atlas brewmagic/art/<file>.png + <file>.json:
    ; comment line (allowed anywhere)
    @ name WxH          header: sprite name [a-z0-9_] and size in pixels
    <H rows of exactly W characters>
Characters: '.' is transparent, 0-9 a-v are palette indices 0..31. Blank lines are allowed
between sprites only. Sprites are shelf-packed in file order with a 1px transparent gap; the
sidecar JSON maps each sprite name to its region {"x", "y", "w", "h"} in the atlas.

Usage (from repo root):
    python3 tools/pixelart.py           build every atlas into brewmagic/art/
    python3 tools/pixelart.py --check   self-test, rebuild into a temp dir and verify the
                                        committed atlases are byte-identical; prints "pixelart: OK"
"""
import json
import re
import struct
import sys
import tempfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "art_src"
OUT_DIR = ROOT / "brewmagic" / "art"
CHARS = "0123456789abcdefghijklmnopqrstuv"
PALETTE_SIZE = len(CHARS)
ATLAS_MIN_WIDTH = 256
GAP = 1
HEADER = re.compile(r"@ ([a-z0-9_]+) (\d+)x(\d+)$")
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


class PixelArtError(Exception):
    pass


def where(path, line):
    try:
        return f"{Path(path).resolve().relative_to(ROOT)}:{line}"
    except ValueError:
        return f"{path}:{line}"


def parse_palette(text, path):
    """Returns the palette as a list of (r, g, b); rejects anything but 32 unique colours."""
    colours = []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split(";", 1)[0].strip()
        if not line:
            continue
        if not re.fullmatch(r"#[0-9a-fA-F]{6}", line):
            raise PixelArtError(f"{where(path, n)}: expected '#rrggbb', got {line!r}")
        rgb = tuple(int(line[i:i + 2], 16) for i in (1, 3, 5))
        if rgb in colours:
            raise PixelArtError(f"{where(path, n)}: duplicate colour {line} (index {colours.index(rgb)})")
        colours.append(rgb)
    if len(colours) != PALETTE_SIZE:
        raise PixelArtError(f"{where(path, 0)}: palette has {len(colours)} colours, expected {PALETTE_SIZE}")
    return colours


def parse_px(text, path):
    """Returns [(name, w, h, rows)] in file order; rejects unknown chars, ragged rows and size mismatches."""
    sprites, current, start = [], None, 0
    for n, raw in enumerate(text.splitlines(), 1):
        if raw.startswith(";"):
            continue
        if current is not None and len(current[3]) < current[2]:
            name, w, h, rows = current
            if raw.startswith("@") or not raw:
                raise PixelArtError(f"{where(path, n)}: sprite '{name}' declared {w}x{h} at line {start} but has only {len(rows)} rows")
            if len(raw) != w:
                raise PixelArtError(f"{where(path, n)}: ragged row in '{name}': {len(raw)} chars, expected {w}")
            for col, ch in enumerate(raw, 1):
                if ch != "." and ch not in CHARS:
                    raise PixelArtError(f"{where(path, n)}: unknown char {ch!r} at column {col} in '{name}' (use '.' or 0-9 a-v)")
            rows.append(raw)
            continue
        if not raw.strip():
            continue
        m = HEADER.match(raw)
        if not m:
            what = f"row outside a sprite (sprite '{current[0]}' is {current[1]}x{current[2]})" if current else "expected '@ name WxH' header"
            raise PixelArtError(f"{where(path, n)}: {what}: {raw[:40]!r}")
        name, w, h = m.group(1), int(m.group(2)), int(m.group(3))
        if w == 0 or h == 0:
            raise PixelArtError(f"{where(path, n)}: sprite '{name}' has an empty size {w}x{h}")
        if any(s[0] == name for s in sprites):
            raise PixelArtError(f"{where(path, n)}: duplicate sprite name '{name}'")
        current, start = (name, w, h, []), n
        sprites.append(current)
    if current is not None and len(current[3]) < current[2]:
        raise PixelArtError(f"{where(path, start)}: sprite '{current[0]}' declared {current[1]}x{current[2]} but has only {len(current[3])} rows")
    if not sprites:
        raise PixelArtError(f"{where(path, 1)}: no sprites")
    return sprites


def pack(sprites):
    """Shelf-packs sprites in order; returns (atlas_w, atlas_h, {name: (x, y, w, h)})."""
    atlas_w = max(ATLAS_MIN_WIDTH, max(w for _, w, _, _ in sprites))
    regions, x, y, shelf_h = {}, 0, 0, 0
    for name, w, h, _ in sprites:
        if x and x + w > atlas_w:
            x, y, shelf_h = 0, y + shelf_h + GAP, 0
        regions[name] = (x, y, w, h)
        x += w + GAP
        shelf_h = max(shelf_h, h)
    return atlas_w, y + shelf_h, regions


def png_chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def write_png(w, h, rgba):
    """Encodes 8-bit RGBA pixels (bytes, row-major) as a PNG with filter 0 on every row."""
    assert len(rgba) == w * h * 4
    raw = b"".join(b"\x00" + rgba[y * w * 4:(y + 1) * w * 4] for y in range(h))
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    # ponytail: byte-identical only for the same zlib build; zlib-ng hosts will differ (pixels still match).
    return PNG_SIGNATURE + png_chunk(b"IHDR", ihdr) + png_chunk(b"IDAT", zlib.compress(raw, 9)) + png_chunk(b"IEND", b"")


def read_png(data):
    """Decodes an 8-bit RGBA non-interlaced PNG; returns (w, h, rgba bytes)."""
    if not data.startswith(PNG_SIGNATURE):
        raise PixelArtError("not a PNG")
    pos, idat, ihdr = len(PNG_SIGNATURE), b"", None
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if struct.unpack(">I", data[pos + 8 + length:pos + 12 + length])[0] != zlib.crc32(kind + body):
            raise PixelArtError(f"bad CRC in {kind!r} chunk")
        if kind == b"IHDR":
            ihdr = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
        pos += 12 + length
    if ihdr is None or ihdr[2:] != (8, 6, 0, 0, 0):
        raise PixelArtError(f"unsupported PNG header {ihdr} (need 8-bit RGBA, not interlaced)")
    w, h = ihdr[0], ihdr[1]
    raw, stride, out, prev = zlib.decompress(idat), w * 4, bytearray(), bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b, c = prev[i], prev[i - 4] if i >= 4 else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
            elif f != 0:
                raise PixelArtError(f"unknown PNG filter {f} on row {y}")
        out += line
        prev = line
    return w, h, bytes(out)


def compile_atlas(path, palette):
    """Returns (png bytes, json text, sprite count) for one .px source."""
    sprites = parse_px(path.read_text(encoding="utf-8"), path)
    atlas_w, atlas_h, regions = pack(sprites)
    rgba = bytearray(atlas_w * atlas_h * 4)
    for name, w, h, rows in sprites:
        x0, y0 = regions[name][:2]
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch != ".":
                    i = ((y0 + y) * atlas_w + x0 + x) * 4
                    rgba[i:i + 4] = bytes(palette[CHARS.index(ch)]) + b"\xff"
    meta = {
        "source": f"art_src/{path.name}",
        "texture": f"{path.stem}.png",
        "size": [atlas_w, atlas_h],
        "sprites": {name: dict(zip("xywh", r)) for name, r in regions.items()},
    }
    return write_png(atlas_w, atlas_h, bytes(rgba)), json.dumps(meta, indent=1) + "\n", len(sprites)


def build(out_dir):
    """Compiles every art_src/*.px into out_dir; returns {filename: bytes}."""
    palette_path = SRC_DIR / "palette.hex"
    palette = parse_palette(palette_path.read_text(encoding="utf-8"), palette_path)
    sources = sorted(SRC_DIR.glob("*.px"))
    if not sources:
        raise PixelArtError(f"no .px sources in {SRC_DIR}")
    out_dir.mkdir(parents=True, exist_ok=True)
    files, count = {}, 0
    for path in sources:
        png, meta, n = compile_atlas(path, palette)
        files[f"{path.stem}.png"], files[f"{path.stem}.json"] = png, meta.encode("utf-8")
        count += n
    for name, data in files.items():
        (out_dir / name).write_bytes(data)
    return files, count, palette


def self_test():
    """Asserts the PNG writer/reader round-trip and every parser rejection."""
    rgba = bytes(range(3 * 2 * 4))
    w, h, back = read_png(write_png(3, 2, rgba))
    assert (w, h, back) == (3, 2, rgba)
    # Paeth/sub/up filters, which our writer never emits, still decode.
    rows = [bytes([10, 20, 30, 255, 40, 50, 60, 255]), bytes([70, 80, 90, 255, 1, 2, 3, 4])]
    filtered = b"\x01" + rows[0][:4] + bytes((rows[0][i] - rows[0][i - 4]) & 255 for i in range(4, 8))
    filtered += b"\x02" + bytes((rows[1][i] - rows[0][i]) & 255 for i in range(8))
    png = PNG_SIGNATURE + png_chunk(b"IHDR", struct.pack(">IIBBBBB", 2, 2, 8, 6, 0, 0, 0))
    png += png_chunk(b"IDAT", zlib.compress(filtered)) + png_chunk(b"IEND", b"")
    assert read_png(png)[2] == rows[0] + rows[1]
    assert parse_px("@ a 2x1\n0v\n\n@ b 1x2\n.\n5\n", "t.px") == [("a", 2, 1, ["0v"]), ("b", 1, 2, [".", "5"])]
    for bad, needle in (("@ a 2x1\n0w\n", "unknown char 'w'"), ("@ a 2x2\n00\n0\n", "ragged row"),
                        ("@ a 2x2\n00\n", "only 1 rows"), ("@ a 1x1\n0\n0\n", "row outside a sprite"),
                        ("@ a 1x1\n0\n@ a 1x1\n0\n", "duplicate sprite"), ("@ A 1x1\n0\n", "header")):
        try:
            parse_px(bad, "t.px")
        except PixelArtError as e:
            assert needle in str(e) and "t.px:" in str(e), (bad, str(e))
        else:
            raise AssertionError(f"accepted bad source {bad!r}")
    try:
        parse_palette("#000000\n" * PALETTE_SIZE, "p.hex")
    except PixelArtError as e:
        assert "duplicate colour" in str(e)
    else:
        raise AssertionError("accepted duplicate palette colour")
    assert pack([("a", 300, 2, []), ("b", 5, 5, []), ("c", 5, 1, [])]) == (300, 8, {"a": (0, 0, 300, 2), "b": (0, 3, 5, 5), "c": (6, 3, 5, 1)})


def check():
    self_test()
    with tempfile.TemporaryDirectory() as tmp:
        files, _, palette = build(Path(tmp))
    allowed = {bytes(c) + b"\xff" for c in palette}
    problems = []
    for name, data in files.items():
        committed = OUT_DIR / name
        if not committed.exists():
            problems.append(f"{committed.relative_to(ROOT)} missing, run python3 tools/pixelart.py")
        elif committed.read_bytes() != data:
            hint = ""
            if name.endswith(".png") and read_png(committed.read_bytes()) == read_png(data):
                hint = " (pixels identical, only the zlib stream differs)"
            problems.append(f"{committed.relative_to(ROOT)} differs from its source{hint}, run python3 tools/pixelart.py")
        if name.endswith(".png"):
            px = read_png(data)[2]
            for i in range(0, len(px), 4):
                if px[i + 3] and px[i:i + 4] not in allowed:
                    problems.append(f"{name}: pixel {i // 4} colour {px[i:i + 4].hex()} is outside the palette")
                    break
    for meta in sorted(OUT_DIR.glob("*.json")):
        source = json.loads(meta.read_text(encoding="utf-8")).get("source", "")
        if source.startswith("art_src/") and meta.name not in files:
            problems.append(f"{meta.relative_to(ROOT)} is stale: its source {source} no longer exists")
    if problems:
        raise PixelArtError("\n".join(problems))
    print("pixelart: OK")


def main():
    try:
        if sys.argv[1:] == ["--check"]:
            check()
        elif not sys.argv[1:]:
            files, count, _ = build(OUT_DIR)
            print(f"pixelart: wrote {len(files) // 2} atlases ({count} sprites) to {OUT_DIR.relative_to(ROOT)}")
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except PixelArtError as e:
        print(f"pixelart: error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
